// 统计每个城市的场馆类型分布
export interface CityStats {
  code: string;
  name: string;
  total: number;
  basketball: number;
  football: number;
}

export function getCityDescription(city: CityStats): string {
  const tag = getCityTag(city.code);
  const ballTypes = [];
  if (city.basketball > 0) ballTypes.push(`${city.basketball}个篮球场馆`);
  if (city.football > 0) ballTypes.push(`${city.football}个足球场馆`);
  const typeStr = ballTypes.length > 0 ? ballTypes.join('、') : '多个体育场馆';
  
  return `${city.name}${tag}，体育场馆资源丰富。FY体育为您收录${city.name}区共${city.total}家体育场馆（${typeStr}），涵盖室内外篮球馆、足球场、综合体育馆等多种场地类型。真实场馆图片展示，在线查看场地详情和地址信息，方便您快速找到合适的运动场地。`;
}
